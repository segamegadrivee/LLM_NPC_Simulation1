    public static void TraceCurrentContextPipeline(DialogueManager dialogueManager, string runtimeChatInput)
    {
        TraceData data = BuildTraceData(dialogueManager, runtimeChatInput);
        List<ValueTraceRow> valueRows = BuildValueRows(data);
        string report = BuildReport(data, valueRows);

        Debug.Log(report);
        SaveReport(report);
    }

    private static TraceData BuildTraceData(DialogueManager providedDialogueManager, string runtimeChatInput)
    {
        TraceData data = new TraceData();
        data.dialogueManager = providedDialogueManager != null ? providedDialogueManager : FindDialogueManager();
        data.runtimeChatInput = runtimeChatInput ?? string.Empty;

        if (data.dialogueManager != null)
        {
            data.contextRetriever = data.dialogueManager.DebugContextRetriever != null ? data.dialogueManager.DebugContextRetriever : ResolveContextRetriever();
            data.memoryStore = data.dialogueManager.DebugConversationMemoryStore != null ? data.dialogueManager.DebugConversationMemoryStore : ResolveMemoryStore();
            data.openAIClient = data.dialogueManager.DebugOpenAIClient;
            data.mockLLMClient = data.dialogueManager.DebugFallbackMockLLMClient;
            data.currentNpc = data.dialogueManager.currentNpc;
            data.currentNpcTransform = data.dialogueManager.currentNpcTransform;
            data.lastPlayerMessage = data.dialogueManager.LastPlayerMessage ?? string.Empty;
            data.snapshot = data.dialogueManager.LastContextSnapshot;
            data.finalPrompt = data.dialogueManager.LastGeneratedPrompt ?? string.Empty;
        }
        else
        {
            data.contextRetriever = ResolveContextRetriever();
            data.memoryStore = ResolveMemoryStore();
        }

        if (data.snapshot != null)
        {
            data.snapshotOrigin = "DialogueManager.LastContextSnapshot captured after DialogueManager.SendPlayerMessage called ContextRetriever.BuildSnapshot.";
        }
        else if (data.contextRetriever != null && data.currentNpc != null)
        {
            data.snapshot = data.contextRetriever.BuildSnapshot(data.currentNpc, data.currentNpcTransform, data.lastPlayerMessage);
            data.snapshotOrigin = "TRACE-ONLY: rebuilt by ContextRetriever.BuildSnapshot for this report because DialogueManager.LastContextSnapshot was empty.";
            data.usedTraceOnlySnapshot = true;
        }
        else
        {
            data.snapshotOrigin = BuildSnapshotUnavailableReason(data.contextRetriever, data.currentNpc);
        }

        if (data.snapshot != null)
        {
            data.reconstructedPrompt = PromptBuilder.BuildPrompt(data.snapshot);
        }

        if (!string.IsNullOrEmpty(data.finalPrompt))
        {
            data.finalPromptOrigin = "DialogueManager.LastGeneratedPrompt. This is the final prompt most recently passed to ILLMClient.SendPrompt.";
            data.promptWasActuallySent = data.dialogueManager != null && data.dialogueManager.LastContextSnapshot != null;
        }
        else if (!string.IsNullOrEmpty(data.reconstructedPrompt))
        {
            data.finalPrompt = data.reconstructedPrompt;
            data.finalPromptOrigin = "TRACE-ONLY: generated by PromptBuilder.BuildPrompt(snapshot) for this report. It has not been sent to the LLM by the trace button.";
        }
        else
        {
            data.finalPromptOrigin = "NOT AVAILABLE: no final prompt exists and no ContextSnapshot was available to reconstruct one.";
        }

        data.playerState = data.snapshot != null && data.snapshot.playerState != null ? data.snapshot.playerState : FindPlayerState();
        data.worldState = data.snapshot != null && data.snapshot.worldState != null ? data.snapshot.worldState : ResolveWorldState();
        data.sceneObjects = UnityEngine.Object.FindObjectsByType<SceneContextObject>(FindObjectsSortMode.None);
        data.knowledgeEntries = GetKnowledgeEntries(data.contextRetriever);
        data.knowledgeRetrievalEvidence = GetKnowledgeRetrievalEvidence(data);
        return data;
    }

    private static string BuildReport(TraceData data, List<ValueTraceRow> valueRows)
    {
        StringBuilder builder = new StringBuilder();
        builder.AppendLine(ReportTitle);
        builder.AppendLine("Generated At: " + DateTime.Now.ToString("yyyy-MM-dd HH:mm:ss"));
        builder.AppendLine("Persistent Data Path: " + Application.persistentDataPath);
        builder.AppendLine("Snapshot Origin: " + SafeText(data.snapshotOrigin, "NOT AVAILABLE: no snapshot origin."));
        builder.AppendLine("Final Prompt Origin: " + SafeText(data.finalPromptOrigin, "NOT AVAILABLE: no prompt origin."));
        builder.AppendLine("Prompt Was Actually Sent By DialogueManager: " + data.promptWasActuallySent);
        builder.AppendLine();

        AppendCallChain(builder, data);
        AppendValuePropagationMatrix(builder, valueRows);
        AppendPromptAssemblyProof(builder, data);
        AppendKnowledgeRetrievalDecisions(builder, data);
        AppendHardcodedVsDynamic(builder, data);
        AppendSourceCodeReferences(builder, data);
        AppendAutomaticMarkerTest(builder, valueRows);

        return builder.ToString();
    }

    private static void AppendCallChain(StringBuilder builder, TraceData data)
    {
        builder.AppendLine("=== CALL CHAIN ===");

        AppendCallStep(
            builder,
            "1",
            "RuntimeChatUI",
            "DrawInput() / Send()",
            RuntimeChatUIPath,
            "Data enters: visible button click; current RuntimeChatUI inputText = " + FormatValue(data.runtimeChatInput) + "; last sent player message = " + FormatValue(data.lastPlayerMessage) + ".",
            "Data exits: [TRACE CONTEXT PIPELINE] calls ContextPipelineTracer.TraceCurrentContextPipeline(dialogueManager, inputText). Normal chat send calls DialogueManager.SendPlayerMessage(text).");

        AppendCallStep(
            builder,
            "2",
            "DialogueManager",
            "SendPlayerMessage(string text)",
            DialogueManagerPath,
            "Data enters: currentNpc = " + DescribeNpc(data.currentNpc) + "; currentNpcTransform = " + DescribeTransform(data.currentNpcTransform) + "; text = " + FormatValue(data.lastPlayerMessage) + ".",
            "Data exits: LastContextSnapshot = " + DescribeSnapshot(data.snapshot) + "; LastGeneratedPrompt length = " + GetLengthText(data.finalPrompt) + "; LastIntendedLLMProvider = " + GetLastIntendedProvider(data) + "; LastActualLLMProvider = " + GetLastActualProvider(data) + ".");

        AppendCallStep(
            builder,
            "3",
            "ContextRetriever",
            "BuildSnapshot(NPCProfile npc, Transform npcTransform, string playerMessage)",
            ContextRetrieverPath,
            "Data enters: npc = " + DescribeNpc(data.currentNpc) + "; npcTransform = " + DescribeTransform(data.currentNpcTransform) + "; playerMessage = " + FormatValue(data.lastPlayerMessage) + "; KnowledgeBase = " + DescribeKnowledgeBase(data.contextRetriever) + ".",
            "Data exits: " + DescribeSnapshot(data.snapshot) + ".");

        AppendCallStep(
            builder,
            "4",
            "ContextSnapshot",
            "public fields filled by ContextRetriever.BuildSnapshot",
            ContextSnapshotPath,
            "Data enters: direct assignments from NPCProfile, PlayerState, WorldState, nearby SceneContextObjects, retrieved KnowledgeEntries, recent dialogue history, and playerMessage.",
            "Data exits: npcProfile/playerState/worldState/playerMessage plus lists: nearbyObjects=" + GetCountText(data.snapshot != null ? data.snapshot.nearbyObjects : null) + ", retrievedKnowledge=" + GetCountText(data.snapshot != null ? data.snapshot.retrievedKnowledge : null) + ", recentDialogueHistory=" + GetCountText(data.snapshot != null ? data.snapshot.recentDialogueHistory : null) + ".");

        AppendCallStep(
            builder,
            "5",
            "PromptBuilder",
            "BuildPrompt(ContextSnapshot snapshot)",
            PromptBuilderPath,
            "Data enters: ContextSnapshot = " + DescribeSnapshot(data.snapshot) + ".",
            "Data exits: reconstructed prompt length = " + GetLengthText(data.reconstructedPrompt) + "; reconstructed prompt equals final prompt = " + PromptEquals(data.finalPrompt, data.reconstructedPrompt) + ".");

        AppendCallStep(
            builder,
            "6",
            GetProviderClassName(data),
            "SendPrompt(string prompt, Action<string> onResponse)",
            GetProviderFilePath(data),
            GetProviderInputText(data),
            "Data exits: intended provider = " + GetLastIntendedProvider(data) + "; actual provider = " + GetLastActualProvider(data) + "; " + GetProviderResultText(data) + ".");

        builder.AppendLine();
    }

    private static void AppendCallStep(StringBuilder builder, string number, string className, string methodName, string filePath, string enters, string exits)
    {
        builder.AppendLine(number + ". " + className + "." + methodName);
        builder.AppendLine("   Class name: " + className);
        builder.AppendLine("   Method name: " + methodName);
        builder.AppendLine("   File path: " + filePath);
        builder.AppendLine("   " + enters);
        builder.AppendLine("   " + exits);
    }

    private static void AppendValuePropagationMatrix(StringBuilder builder, List<ValueTraceRow> rows)
    {
        builder.AppendLine("=== VALUE PROPAGATION MATRIX ===");

        if (rows == null || rows.Count == 0)
        {
            builder.AppendLine("NOT AVAILABLE: no value rows could be built.");
            builder.AppendLine();
            return;
        }

        for (int i = 0; i < rows.Count; i++)
        {
            ValueTraceRow row = rows[i];
            builder.AppendLine("Value #" + (i + 1));
            builder.AppendLine("- Source object: " + row.sourceObject);
            builder.AppendLine("- Source field: " + row.sourceField);
            builder.AppendLine("- Source value: " + row.sourceValue);
            builder.AppendLine("- Snapshot field where it appears: " + row.snapshotField);
            builder.AppendLine("- Does it appear in final prompt? " + row.appearsInPrompt);
            builder.AppendLine("- Exact prompt excerpt where it appears: " + row.promptExcerpt);
            builder.AppendLine("- Marker: " + row.marker);

            if (!string.IsNullOrEmpty(row.note))
            {
                builder.AppendLine("- Note: " + row.note);
            }
        }

        builder.AppendLine();
    }

