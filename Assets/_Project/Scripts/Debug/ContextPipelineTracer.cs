    private static void AddListRows(List<ValueTraceRow> rows, string prompt, string sourceObject, string sourceField, List<string> values, string snapshotField, bool allowSearch)
    {
        if (values == null || values.Count == 0)
        {
            AddTraceRow(rows, prompt, sourceObject, sourceField, string.Empty, snapshotField, null, allowSearch, null);
