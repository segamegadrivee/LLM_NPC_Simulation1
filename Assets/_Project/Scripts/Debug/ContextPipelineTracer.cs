        AddTraceRow(rows, prompt, sourceObject, "role", npc.role, "snapshot.npcProfile.role", "Role: " + npc.role, inSnapshot, null);
        AddTraceRow(rows, prompt, sourceObject, "personality", npc.personality, "snapshot.npcProfile.personality", "Personality: " + npc.personality, inSnapshot, null);
