        }

        bool wroteValue = false;

        for (int i = 0; i < values.Count; i++)
        {
            if (string.IsNullOrEmpty(values[i]) || values[i].Trim().Length == 0)
            {
                continue;
            }

            wroteValue = true;
            AddTraceRow(rows, prompt, sourceObject, sourceField + "[" + i + "]", values[i], snapshotField + "[" + i + "]", "- " + values[i].Trim(), allowSearch, allowSearch ? null : "NOT USED IN FINAL PROMPT: source object/list is not present in ContextSnapshot.");
        }

        if (!wroteValue)
        {
            AddTraceRow(rows, prompt, sourceObject, sourceField, string.Empty, snapshotField, null, allowSearch, null);
        }
    }

