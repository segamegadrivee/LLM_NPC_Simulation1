    private static void AddTraceRow(List<ValueTraceRow> rows, string prompt, string sourceObject, string sourceField, string sourceValue, string snapshotField, string searchText, bool allowSearch, string note)
    {
        ValueTraceRow row = new ValueTraceRow();
        row.sourceObject = sourceObject;
        row.sourceField = sourceField;
        row.sourceValue = FormatValue(sourceValue);
        row.snapshotField = snapshotField;
        row.note = note;

        if (string.IsNullOrEmpty(sourceValue) || sourceValue.Trim().Length == 0)
        {
            row.appearsInPrompt = "false";
            row.promptExcerpt = "SKIP: value is empty/null.";
            row.marker = "SKIP: " + sourceField + " is empty.";
            rows.Add(row);
            return;
        }

        if (!allowSearch)
        {
            row.appearsInPrompt = "false";
            row.promptExcerpt = "NOT USED IN FINAL PROMPT.";
            row.marker = "FAIL: " + sourceField + " did not propagate into ContextSnapshot/final prompt.";
            rows.Add(row);
            return;
        }

        string effectiveSearchText = string.IsNullOrEmpty(searchText) ? sourceValue : searchText;

        if (string.IsNullOrEmpty(prompt))
        {
            row.appearsInPrompt = "false";
            row.promptExcerpt = "NOT AVAILABLE: final prompt is empty.";
            row.marker = "FAIL: " + sourceField + " could not be checked because final prompt is empty.";
            rows.Add(row);
            return;
        }

        if (ContainsNormalized(prompt, effectiveSearchText))
        {
            row.appearsInPrompt = "true";
            row.promptExcerpt = FindPromptExcerpt(prompt, effectiveSearchText);
            row.marker = "PASS: " + sourceField + " appeared in final prompt.";
        }
        else
        {
            row.appearsInPrompt = "false";
            row.promptExcerpt = "NOT USED IN FINAL PROMPT.";
            row.marker = "FAIL: " + sourceField + " did not appear in final prompt.";
        }

        rows.Add(row);
    }

    private static bool ContainsNormalized(string text, string searchText)
    {
        if (string.IsNullOrEmpty(text) || string.IsNullOrEmpty(searchText))
        {
            return false;
        }

        return NormalizeNewlines(text).Contains(NormalizeNewlines(searchText));
    }

    private static string FindPromptExcerpt(string prompt, string searchText)
    {
        if (string.IsNullOrEmpty(prompt) || string.IsNullOrEmpty(searchText))
        {
            return "NOT AVAILABLE: empty prompt or search text.";
        }

        string normalizedPrompt = NormalizeNewlines(prompt);
        string normalizedSearch = NormalizeNewlines(searchText);
        int index = normalizedPrompt.IndexOf(normalizedSearch, StringComparison.Ordinal);

        if (index < 0)
        {
            return "NOT USED IN FINAL PROMPT.";
        }

        int lineStart = normalizedPrompt.LastIndexOf('\n', Mathf.Max(0, index));
        lineStart = lineStart < 0 ? 0 : lineStart + 1;
        int lineEnd = normalizedPrompt.IndexOf('\n', index);
        lineEnd = lineEnd < 0 ? normalizedPrompt.Length : lineEnd;

        if (normalizedSearch.Contains("\n"))
        {
            return Clip(normalizedSearch, 500);
        }

        return Clip(normalizedPrompt.Substring(lineStart, lineEnd - lineStart), 500);
    }

    private static string ExtractPromptPrefix(string prompt, string endHeader)
    {
        string normalizedPrompt = NormalizeNewlines(prompt);
        int endIndex = FindHeaderIndex(normalizedPrompt, endHeader);

        if (endIndex < 0)
        {
            return "NEEDS MANUAL CHECK: header not found: " + endHeader;
        }

        return Clip(normalizedPrompt.Substring(0, endIndex).TrimEnd(), 4000);
    }

    private static string ExtractPromptRange(string prompt, string startHeader, string endHeader)
    {
        string normalizedPrompt = NormalizeNewlines(prompt);
        int startIndex = FindHeaderIndex(normalizedPrompt, startHeader);
        int endIndex = FindHeaderIndex(normalizedPrompt, endHeader);

        if (startIndex < 0)
        {
            return "NEEDS MANUAL CHECK: start header not found: " + startHeader;
        }

        if (endIndex < 0 || endIndex <= startIndex)
        {
            return Clip(normalizedPrompt.Substring(startIndex).TrimEnd(), 4000);
        }

        return Clip(normalizedPrompt.Substring(startIndex, endIndex - startIndex).TrimEnd(), 4000);
    }

    private static string ExtractPromptSection(string prompt, string sectionHeader, string nextSectionHeader)
    {
        string normalizedPrompt = NormalizeNewlines(prompt);
        int startIndex = FindHeaderIndex(normalizedPrompt, sectionHeader);

        if (startIndex < 0)
        {
            return "NEEDS MANUAL CHECK: section header not found: " + sectionHeader;
        }

        int endIndex = string.IsNullOrEmpty(nextSectionHeader) ? -1 : FindHeaderIndex(normalizedPrompt, nextSectionHeader);

        if (endIndex < 0 || endIndex <= startIndex)
        {
            return Clip(normalizedPrompt.Substring(startIndex).TrimEnd(), 4000);
        }

        return Clip(normalizedPrompt.Substring(startIndex, endIndex - startIndex).TrimEnd(), 4000);
    }

    private static int FindHeaderIndex(string text, string header)
    {
        if (string.IsNullOrEmpty(text) || string.IsNullOrEmpty(header))
        {
            return -1;
        }

        if (text.StartsWith(header + "\n", StringComparison.Ordinal) || text == header)
        {
            return 0;
        }

        int index = text.IndexOf("\n" + header + "\n", StringComparison.Ordinal);

        if (index >= 0)
        {
            return index + 1;
        }

        index = text.IndexOf("\n" + header, StringComparison.Ordinal);
        return index >= 0 ? index + 1 : -1;
    }

    private static string NormalizeNewlines(string value)
    {
        return string.IsNullOrEmpty(value) ? string.Empty : value.Replace("\r\n", "\n").Replace("\r", "\n");
    }

    private static string Clip(string value, int maxLength)
    {
        if (string.IsNullOrEmpty(value))
        {
            return "None";
        }

        if (value.Length <= maxLength)
        {
            return value;
        }

        return value.Substring(0, Mathf.Max(0, maxLength)) + "...";
    }

