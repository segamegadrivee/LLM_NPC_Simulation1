    private static List<ValueTraceRow> BuildValueRows(TraceData data)
    {
        List<ValueTraceRow> rows = new List<ValueTraceRow>();
        string prompt = data.finalPrompt ?? string.Empty;

        AddNpcProfileRows(rows, data, prompt);
        AddPlayerStateRows(rows, data, prompt);
        AddNpcStateRows(rows, data, prompt);
        AddWorldStateRows(rows, data, prompt);
        AddWorldEventRows(rows, data, prompt);
        AddSceneContextObjectRows(rows, data, prompt);
        AddKnowledgeEntryRows(rows, data, prompt);
        AddDialogueMemoryRows(rows, data, prompt);
        AddPlayerMessageRows(rows, data, prompt);

        return rows;
    }

    private static void AddNpcProfileRows(List<ValueTraceRow> rows, TraceData data, string prompt)
