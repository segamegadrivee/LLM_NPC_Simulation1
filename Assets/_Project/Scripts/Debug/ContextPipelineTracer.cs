        if (!data.promptWasActuallySent)
        {
            return "Data enters: NOT AVAILABLE: no final prompt has been sent by DialogueManager yet, or this prompt was reconstructed for tracing only. Trace button does not call SendPrompt.";
        }

        return "Data enters: final prompt from DialogueManager.LastGeneratedPrompt; prompt length = " + GetLengthText(data.finalPrompt) + ".";
    }

    private static string GetLastIntendedProvider(TraceData data)
    {
        if (data.dialogueManager == null)
        {
            return "NOT AVAILABLE: DialogueManager is null.";
        }

        return SafeText(data.dialogueManager.LastIntendedLLMProvider, data.dialogueManager.CurrentLLMName);
    }

    private static string GetLastActualProvider(TraceData data)
    {
        if (data.dialogueManager == null)
        {
            return "NOT AVAILABLE: DialogueManager is null.";
        }

        return SafeText(data.dialogueManager.LastActualLLMProvider, "None");
    }

    private static string PromptEquals(string finalPrompt, string reconstructedPrompt)
    {
        if (string.IsNullOrEmpty(finalPrompt) || string.IsNullOrEmpty(reconstructedPrompt))
        {
            return "false (NOT AVAILABLE: one prompt string is empty)";
        }

        return string.Equals(NormalizeNewlines(finalPrompt), NormalizeNewlines(reconstructedPrompt), StringComparison.Ordinal) ? "true" : "false";
    }

    private static string GetCountText<T>(List<T> values)
    {
        return values != null ? values.Count.ToString() : "NOT AVAILABLE";
    }

    private static string GetLengthText(string value)
    {
        return value != null ? value.Length.ToString() : "NOT AVAILABLE";
    }

    private static string FormatValue(string value)
    {
        if (string.IsNullOrEmpty(value))
        {
            return "SKIP: empty/null";
        }

        return Clip(NormalizeNewlines(value), 500);
    }

    private static string SafeText(string value, string fallback)
    {
        return string.IsNullOrEmpty(value) || value.Trim().Length == 0 ? fallback : value;
    }

    private static string BoolText(bool value)
    {
        return value ? "true" : "false";
    }

    private static void SaveReport(string report)
    {
        try
        {
            Directory.CreateDirectory(Application.persistentDataPath);
            string fileName = "ContextPipelineTrace_" + DateTime.Now.ToString("yyyyMMdd_HHmmss") + ".txt";
            string filePath = Path.Combine(Application.persistentDataPath, fileName);
            File.WriteAllText(filePath, report, Encoding.UTF8);
            Debug.Log("CONTEXT PIPELINE TRACE REPORT saved to: " + filePath);
        }
        catch (Exception exception)
        {
            Debug.LogError("Failed to save CONTEXT PIPELINE TRACE REPORT: " + exception.Message);
        }
    }

